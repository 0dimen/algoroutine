"""One reviewed catalog per locale -> browser, watchOS and Wear OS resources.
Legacy Korean msgids are stable identifiers, not the runtime fallback language.
"""
import json,re
from pathlib import Path
ROOT=Path(__file__).resolve().parents[1]
CAT={p.stem:json.loads(p.read_text()) for p in sorted((ROOT/'localization').glob('*.json')) if p.stem!='registry'}
REG=json.loads((ROOT/'localization/registry.json').read_text())
assert REG.keys()==CAT.keys()
base=CAT['en']
for lang,values in CAT.items():
 assert values.keys()==base.keys(), f'{lang}: missing or extra translation keys'
 for key,value in values.items():
  assert value and set(re.findall(r'\{\w+\}',value))==set(re.findall(r'\{\w+\}',base[key])),f'{lang}:{key} placeholder mismatch'
def write(path,text): (ROOT/path).write_text(text)
write('apps/mobile/web/messages.js','// Generated by scripts/generate_localizations.py\nexport const messages = '+json.dumps(CAT,ensure_ascii=False,indent=2)+';\nexport const languages = '+json.dumps(REG,ensure_ascii=False)+';\n')
# Native dictionaries are generated. Only runtime helpers below are maintained here.
ks=lambda s:json.dumps(s,ensure_ascii=False).replace('$','\\$')
km='mapOf('+','.join(ks(lang)+' to mapOf('+','.join(ks(k)+' to '+ks(v) for k,v in d.items())+')' for lang,d in CAT.items())+')'
write('apps/watch-proof/wearApp/src/main/java/app/algoroutine/wear/AppLanguage.kt','''// Generated by scripts/generate_localizations.py
package app.algoroutine.wear
import android.content.Context
import androidx.compose.runtime.*
object AppLanguage {
 var code by mutableStateOf("en"); private set
 private var context:Context?=null
 fun configure(value:Context, override:String?=null){context=value.applicationContext;code=normalize(override ?: value.getSharedPreferences("language",0).getString("code","en"))}
 fun normalize(value:String?)=if(catalog.containsKey(value))value!! else "en"
 fun select(value:String){code=normalize(value);context?.getSharedPreferences("language",0)?.edit()?.putString("code",code)?.apply()}
 val codes get()=catalog.keys.toList()
 val displayName get()=languageNames[code] ?: "English"
 val speechTag:String get()=speechTags[code] ?: "en-US"
 fun cycle(){select(codes[(codes.indexOf(code)+1)%codes.size])}
}
private val languageNames='''+'mapOf('+','.join(ks(k)+' to '+ks(v['nativeName']) for k,v in REG.items())+')'+'''
private val speechTags='''+'mapOf('+','.join(ks(k)+' to '+ks(v['speechTag']) for k,v in REG.items())+')'+'''
private val catalog='''+km+'''
fun tr(key:String,vararg args:Pair<String,Any>):String {
 var value=catalog[AppLanguage.code]?.get(key) ?: catalog.getValue("en")[key] ?: key
 args.forEach{(k,v)->value=value.replace("{$k}",v.toString())};return value
}
''')
sm='['+','.join(json.dumps(lang)+':['+','.join(json.dumps(k,ensure_ascii=False)+':'+json.dumps(v,ensure_ascii=False) for k,v in d.items())+']' for lang,d in CAT.items())+']'
write('apps/watch-proof/appleWatch/AppLanguage.swift','''// Generated by scripts/generate_localizations.py
import SwiftUI
private let catalog:[String:[String:String]]='''+sm+'''
let appLanguages:[String:String]='''+'['+','.join(json.dumps(k)+':'+json.dumps(v['nativeName'],ensure_ascii=False) for k,v in REG.items())+']'+'''
func appLanguage()->String {
 let saved=UserDefaults.standard.string(forKey:"app.language") ?? "en"
 return catalog[saved] != nil ? saved : "en"
}
func L(_ key:String,_ args:[String:String]=[:])->String {
 var value=catalog[appLanguage()]?[key] ?? catalog["en"]?[key] ?? key
 for (name,text) in args {value=value.replacingOccurrences(of:"{\\(name)}",with:text)}
 return value
}
''')
print('Generated',len(base),'messages for',','.join(CAT))
